#!/usr/bin/env node
// Heavy style assets (music-bed WAVs, reference MP4s, source archives) live in GitHub Releases, not in git.
// assets/manifest.json lists every such file with its SHA-256; `fetch` downloads and verifies them on any OS.
//   node scripts/assets.mjs status            what is present / missing / different
//   node scripts/assets.mjs fetch [--only <path-prefix>]   download missing files from the release
//   node scripts/assets.mjs pack --release <tag>   (maintainer) list new heavy files, update manifest + .gitignore
// Existing files are never overwritten: a local file with a different hash is reported, not replaced.
import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import {fileURLToPath} from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(ROOT, "assets", "manifest.json");
const GITIGNORE = path.join(ROOT, ".gitignore");
/** Folders whose small files are in git and whose heavy files go to a release. */
export const STYLE_DIRS = ["data/templates", "data/sound-packs", "data/branding", "data/backgrounds", "data/models"];
const THRESHOLD = 4 * 1024 * 1024;
const SKIP = new Set([".DS_Store", "Thumbs.db"]);
const BEGIN = "# >>> heavy style assets (GitHub Release, see assets/manifest.json) — generated by scripts/assets.mjs pack";
const END = "# <<< heavy style assets";

const posix = (p) => p.split(path.sep).join("/");
const abs = (rel) => path.join(ROOT, ...rel.split("/"));
const readManifest = () => fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, "utf8")) : {version: 1, repo: "x7uned/motionstudio", files: []};
const sha256 = (file) => new Promise((resolve, reject) => {
  const h = crypto.createHash("sha256");
  fs.createReadStream(file).on("data", (d) => h.update(d)).on("error", reject).on("end", () => resolve(h.digest("hex")));
});
const assetName = (rel, sha) => `${sha.slice(0, 16)}-${path.posix.basename(rel).replace(/[^A-Za-z0-9._-]+/g, "_")}`;
const mb = (n) => `${(n / 1048576).toFixed(1)} МБ`;

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, {withFileTypes: true})) {
    if (SKIP.has(e.name) || e.name === "__pycache__") continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else if (e.isFile()) out.push(p);
  }
  return out;
}

async function state(entry) {
  const file = abs(entry.path);
  if (!fs.existsSync(file)) return "missing";
  if (fs.statSync(file).size !== entry.bytes) return "different";
  return (await sha256(file)) === entry.sha256 ? "ok" : "different";
}

async function status() {
  const m = readManifest();
  const counts = {ok: 0, missing: 0, different: 0};
  for (const f of m.files) {
    const s = await state(f);
    counts[s]++;
    if (s !== "ok") console.log(`  ${s === "missing" ? "нет" : "ОТЛИЧАЕТСЯ"} ${f.path} (${mb(f.bytes)}, ${f.release})`);
  }
  console.log(`Тяжёлые файлы стилей: ${m.files.length} · на месте ${counts.ok} · нет ${counts.missing} · отличаются ${counts.different}`);
  if (counts.missing) console.log("Скачать: npm run assets -- fetch");
  return counts.different ? 1 : 0;
}

async function download(url, to) {
  const res = await fetch(url, {redirect: "follow"});
  if (!res.ok || !res.body) throw new Error(`${res.status} ${res.statusText} — ${url}`);
  const tmp = `${to}.part`;
  await fsp.mkdir(path.dirname(to), {recursive: true});
  const out = fs.createWriteStream(tmp);
  const reader = res.body.getReader();
  for (;;) {
    const {done, value} = await reader.read();
    if (done) break;
    if (!out.write(value)) await new Promise((r) => out.once("drain", r));
  }
  await new Promise((resolve, reject) => out.end((e) => (e ? reject(e) : resolve())));
  return tmp;
}

async function fetchAll(only) {
  const m = readManifest();
  let got = 0, failed = 0;
  for (const f of m.files) {
    if (only && !f.path.startsWith(only)) continue;
    const s = await state(f);
    if (s === "ok") continue;
    if (s === "different") { console.log(`  пропущено (локальный файл отличается, не перезаписываю): ${f.path}`); failed++; continue; }
    const url = `https://github.com/${m.repo}/releases/download/${f.release}/${f.asset}`;
    process.stdout.write(`  ${f.path} (${mb(f.bytes)}) … `);
    try {
      const tmp = await download(url, abs(f.path));
      const got256 = await sha256(tmp);
      if (got256 !== f.sha256) { await fsp.rm(tmp, {force: true}); throw new Error(`SHA-256 не совпал (${got256.slice(0, 12)}…)`); }
      await fsp.rename(tmp, abs(f.path));
      console.log("ok"); got++;
    } catch (e) { console.log(`ошибка: ${e instanceof Error ? e.message : e}`); failed++; }
  }
  console.log(`Скачано: ${got}${failed ? ` · не удалось: ${failed}` : ""}`);
  return failed ? 1 : 0;
}

async function pack(release) {
  if (!release) throw new Error("node scripts/assets.mjs pack --release assets-vN");
  const m = readManifest();
  const known = new Map(m.files.map((f) => [f.path, f]));
  const fresh = [];
  for (const dir of STYLE_DIRS) for (const file of walk(abs(dir))) {
    const bytes = fs.statSync(file).size;
    if (bytes < THRESHOLD) continue;
    const rel = posix(path.relative(ROOT, file));
    const sha = await sha256(file);
    const prev = known.get(rel);
    if (prev) { if (prev.sha256 !== sha) throw new Error(`${rel} изменился после выпуска ${prev.release}: пакеты неизменяемы, сохраните новую версию.`); continue; }
    const entry = {path: rel, bytes, sha256: sha, release, asset: assetName(rel, sha)};
    m.files.push(entry); fresh.push(entry);
  }
  m.files.sort((a, b) => a.path.localeCompare(b.path));
  await fsp.mkdir(path.dirname(MANIFEST), {recursive: true});
  await fsp.writeFile(MANIFEST, `${JSON.stringify(m, null, 1)}\n`);
  const block = [BEGIN, ...m.files.map((f) => `/${f.path}`), END].join("\n");
  const gi = fs.readFileSync(GITIGNORE, "utf8");
  const re = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
  await fsp.writeFile(GITIGNORE, re.test(gi) ? gi.replace(re, block) : `${gi.trimEnd()}\n\n${block}\n`);
  // Upload list for the maintainer: gh release upload <tag> <file>#<asset> (asset names are content-addressed).
  const list = path.join(ROOT, "assets", `upload-${release}.txt`);
  await fsp.writeFile(list, fresh.map((f) => `${f.path}\t${f.asset}`).join("\n") + (fresh.length ? "\n" : ""));
  console.log(`Новых тяжёлых файлов: ${fresh.length} (${mb(fresh.reduce((s, f) => s + f.bytes, 0))}) → ${release}. Список: ${posix(path.relative(ROOT, list))}`);
  return 0;
}

const [cmd = "status", ...rest] = process.argv.slice(2);
const flag = (k) => { const i = rest.indexOf(`--${k}`); return i >= 0 ? rest[i + 1] : undefined; };
const run = {status, fetch: () => fetchAll(flag("only")), pack: () => pack(flag("release"))}[cmd];
if (!run) { console.error("node scripts/assets.mjs status | fetch [--only <prefix>] | pack --release <tag>"); process.exit(1); }
run().then((code) => process.exit(code), (e) => { console.error(`Ошибка: ${e instanceof Error ? e.message : e}`); process.exit(1); });
