export const SONIC_CELLS = 39, ANCHOR_COL = 17, SLOT_W = 44;
/** every grid normalised so its lowest drawn row sits on row 38 (the ground line) — the feet anchor is (col 17, row 39) */
export const POSE = {};
for (const [k, g] of Object.entries(GRIDS)) {
  if (g.length !== 39 || g.some((r) => r.length !== SLOT_W)) throw new Error(`sonic grid ${k}`);
  let last = 0; g.forEach((r, j) => { if (/[^.]/.test(r)) last = j; });
  const sh = 38 - last; POSE[k] = sh > 0 ? [...Array.from({ length: sh }, () => ".".repeat(SLOT_W)), ...g.slice(0, 39 - sh)] : g;
}
const mirrorG = (g) => g.map((r) => [...r].reverse().join(""));
/** rotate a grid about the feet anchor by a multiple of 45° (nearest-neighbour on whole cells: cells stay squares) */
const ROT = new Map();
function rotated(name, k8, mir) {
  const key = name + "|" + k8 + "|" + mir; let v = ROT.get(key); if (v) return v;
  const src = mir ? mirrorG(POSE[name]) : POSE[name], ax = mir ? SLOT_W - 1 - ANCHOR_COL + 0.5 : ANCHOR_COL + 0.5, ay = 39;
  const a = (k8 * Math.PI) / 4, ca = Math.round(Math.cos(a) * 1e9) / 1e9, sa = Math.round(Math.sin(a) * 1e9) / 1e9, S = 48, out = [];
  // output cell (i, j) in a 2S × 2S box around the anchor; the source cell is the inverse rotation of its centre
  for (let j = -S; j < S; j++) { let row = ""; for (let i = -S; i < S; i++) { const x = i + 0.5, y = j + 0.5, sx = ca * x + sa * y, sy = -sa * x + ca * y, gi = Math.floor(sx + ax), gj = Math.floor(sy + ay); row += gj >= 0 && gj < 39 && gi >= 0 && gi < SLOT_W ? src[gj][gi] : "."; } out.push(row); }
  v = { g: out, ox: S, oy: S }; ROT.set(key, v); return v;
}
/** cell-dither choice between two grids of the same size (k = weight of B) */
function blend2(A, B, k, salt = 0) {
  const out = []; for (let j = 0; j < A.length; j++) { let row = ""; for (let i = 0; i < A[j].length; i++) row += bayer(i + salt, j + 2 * salt) < k ? B[j][i] : A[j][i]; out.push(row); } return out;
}
/**
 * Sonic with his feet (anchor) at (fx, fy), integer cell size N. poses: [[name, weight, mirror?], …] (the two strongest are cell-dithered,
 * so a pose change is a 2–3 frame Bayer dissolve when the weights ease); o: { mir (face left), rot (radians, snapped to 45°:
 * the feet stay on the anchor and «up» turns, for the loop), a (presence: cell dither), col (flat rgb: silhouette) }.
 * Returns { box, x0, y0, N, cols, rows } (box in screen px).
 */
export function drawSonic(c, fx, fy, N, poses, o = {}) {
  N = Math.max(1, Math.round(N)); const a = o.a ?? 1; if (a <= 0) return null;
  const list = (Array.isArray(poses) ? poses : [[poses, 1]]).filter(([, w]) => w > 0.001).sort((p, q) => q[1] - p[1]);
  const k8 = (((Math.round(((o.rot ?? 0) / (Math.PI / 4))) % 8) + 8) % 8), mir = !!o.mir;
  const A = rotated(list[0][0], k8, list[0][2] ?? mir); let G = A.g;
  if (list[1]) { const B = rotated(list[1][0], k8, list[1][2] ?? mir), k = list[1][1] / (list[0][1] + list[1][1]); G = blend2(A.g, B.g, k, 1); }
  const x0 = Math.round(fx) - Math.round(A.ox * N), y0 = Math.round(fy) - A.oy * N;
  let bx0 = 1e9, by0 = 1e9, bx1 = -1e9, by1 = -1e9;
  for (let j = 0; j < G.length; j++) { const row = G[j]; for (let i = 0; i < row.length; i++) {
    const ch = row[i]; if (ch === ".") continue; if (a < 1 && a <= bayer(i + 2, j + 1)) continue;
    const col = o.col ?? PAL[ch]; const X = x0 + i * N, Y = y0 + j * N;
    for (let y = Math.max(0, Y); y < Math.min(c.h, Y + N); y++) { const q0 = (y * c.w) * 3; for (let x = Math.max(0, X); x < Math.min(c.w, X + N); x++) { const q = q0 + x * 3; c.d[q] = col[0]; c.d[q + 1] = col[1]; c.d[q + 2] = col[2]; } }
    bx0 = Math.min(bx0, X); by0 = Math.min(by0, Y); bx1 = Math.max(bx1, X + N); by1 = Math.max(by1, Y + N);
  } }
  return { box: bx1 > bx0 ? { x0: bx0, y0: by0, x1: bx1, y1: by1 } : null, x0, y0, N, cols: G[0].length, rows: G.length, k8 };
}
/** a flat dark shadow strip under a sprite (1–2 cells of N tall, dithered ends); k = presence, wc = width in cells */
export function spriteShadow(c, fx, fy, N, k = 1, wc = 22, rows = 1) {
  if (k <= 0.02) return; N = Math.max(1, Math.round(N));
  const half = Math.round((wc / 2) * N), y0 = Math.round(fy) - Math.ceil(N / 3), h = Math.max(2, Math.round(N * rows)), X = Math.round(fx);
  for (let y = y0; y < y0 + h; y++) for (let x = X - half - N; x < X + half + N; x++) {
    if (x < 0 || y < 0 || x >= c.w || y >= c.h) continue;
    const edge = x < X - half || x >= X + half; const p = k * (edge ? 0.45 : 1); if (p < 1 && p <= bayer(x, y)) continue;
    const i = (y * c.w + x) * 3; c.d[i] = c.d[i] * 0.5 + 18; c.d[i + 1] = c.d[i + 1] * 0.48 + 14; c.d[i + 2] = c.d[i + 2] * 0.55 + 34;
  }
}
/** the run cycle at game cadence: which frame of a 4-frame cycle at phase ph (frames), the change frame is a 50 % cell dither */
export function cycle(names, ph, pp) {
  const n = names.length, i = ((Math.floor(ph) % n) + n) % n, j = ((Math.floor(pp) % n) + n) % n;
  return i !== j ? [[names[j], 0.5], [names[i], 0.5]] : [[names[i], 1]];
}
