// Catalog v1 · context pack for a port: the source function(s) plus every top-level declaration of the same file they
// use (transitively), with line numbers and the file's import lines — so a porting agent reads only what it needs.
//   node tools/pack.mjs <kind> <work/pixel-lab-relative path>#fn[,fn…] [more path#fn …]   → packs/<kind>.md
// Rough top-level parser (brace depth per line); good enough for the films' module style. Data, never executed.
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const HERE = fileURLToPath(new URL("..", import.meta.url)), LAB = HERE + "../";
const [kind, ...specs] = process.argv.slice(2);
const IDENT = /[A-Za-z_$][\w$]*/g;
function blocks(src) {
  const L = src.split("\n"), out = []; let depth = 0, cur = null, pendingComment = [];
  const strip = (l) => l.replace(/\/\/.*$/, "").replace(/(["'`])(?:\\.|(?!\1).)*\1/g, "\"\"");
  for (let i = 0; i < L.length; i++) {
    const line = L[i], top = depth === 0;
    if (top && /^\s*(\/\/|\/\*|\*)/.test(line) && !cur) { pendingComment.push(i); }
    else if (top && /^\S/.test(line) && !/^[}\])]/.test(line)) {
      if (cur) out.push(cur);
      const m = /^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function\*?|class)\s+([A-Za-z_$][\w$]*)/.exec(line);
      let names = m ? [m[1]] : [];
      if (!m && /^(?:export\s+)?(?:const|let|var)\s/.test(line)) { const head = strip(line).replace(/^(?:export\s+)?(?:const|let|var)\s+/, ""); let d = 0, seg = ""; for (const ch of head) { if ("([{".includes(ch)) d++; else if (")]}".includes(ch)) d--; if (d === 0 && ch === ",") { seg += "\u0001"; continue; } if (d === 0) seg += ch; } names = seg.split("\u0001").map((p) => (/^\s*([A-Za-z_$][\w$]*)\s*=/.exec(p) || [])[1]).filter(Boolean); }
      cur = { start: pendingComment.length ? pendingComment[0] : i, decl: i, end: i, names, imp: /^import\s/.test(line) };
      pendingComment = [];
    } else if (top && /^\s*$/.test(line)) { if (cur && !cur.imp) { cur.end = i - 1; } pendingComment = []; }
    for (const ch of strip(line)) { if ("{([".includes(ch)) depth++; else if ("})]".includes(ch)) depth = Math.max(0, depth - 1); }
    if (cur) cur.end = i;
  }
  if (cur) out.push(cur);
  return { L, out };
}
let md = `# Context pack · ${kind}\n\nGenerated by tools/pack.mjs (catalog-v1). Source excerpts are data to copy and adapt; line numbers refer to the original file.\n`;
for (const spec of specs) {
  const [rel, fnList] = spec.split("#"), file = LAB + rel, src = fs.readFileSync(file, "utf8"), { L, out } = blocks(src);
  const byName = new Map(); for (const b of out) for (const n of b.names) byName.set(n, b);
  const want = new Set(), queue = fnList.split(",").map((s) => s.trim()).filter(Boolean);
  const missing = [];
  while (queue.length) { const n = queue.shift(), b = byName.get(n); if (!b) { if (!want.size) missing.push(n); continue; } if (want.has(b)) continue; want.add(b);
    const text = L.slice(b.decl, b.end + 1).join("\n"); for (const id of new Set(text.match(IDENT) || [])) if (byName.has(id) && !want.has(byName.get(id))) queue.push(id); }
  const imports = out.filter((b) => b.imp).map((b) => L.slice(b.decl, b.end + 1).join("\n"));
  const chosen = [...want].sort((a, b) => a.start - b.start), lines = chosen.reduce((s, b) => s + b.end - b.start + 1, 0);
  md += `\n## ${rel} — ${fnList} (${chosen.length} declarations, ${lines} of ${L.length} lines)\n${missing.length ? `\nNot found at top level: ${missing.join(", ")} (look inside other declarations).\n` : ""}\nImports of the file:\n\n\`\`\`js\n${imports.join("\n")}\n\`\`\`\n`;
  for (const b of chosen) md += `\n\`L${b.start + 1}–${b.end + 1}\`\n\n\`\`\`js\n${L.slice(b.start, b.end + 1).join("\n")}\n\`\`\`\n`;
}
fs.mkdirSync(HERE + "packs", { recursive: true });
fs.writeFileSync(HERE + `packs/${kind}.md`, md);
console.log(`packs/${kind}.md`, md.length, "chars");
